import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

const { mockGet, mockPost } = vi.hoisted(() => ({ mockGet: vi.fn(), mockPost: vi.fn() }));
vi.mock("axios", () => ({ default: {
    create: () => ({ get: mockGet, post: mockPost }),
    isAxiosError: (error: unknown) => !!error && typeof error === "object" && "isAxiosError" in error,
} }));

import {
    getAtlasErrorMessage,
    getProviderActionHistory,
    getProviderActionHistoryEntry,
    getProviderActionHistoryProviders,
    getProviderActionHistorySummary,
} from "./atlas";
import nativeFixture from "../test/actionHistory.fixture.json";
import { ActionHistoryResponseError } from "./actionHistoryResponse";

function entry(patch: Record<string, unknown> = {}): Record<string, unknown> {
    return { id: "audit/one", provider_id: "fixture", provider_name: "Example provider",
        action_id: "restart-service", action_label: "Restart service", status: "succeeded", success: true,
        message: "Service restarted.", confirmed: true, destructive: false, parameter_names: [], request_id: null,
        started_at: "2026-10-01T12:00:00Z", completed_at: "2026-10-01T12:00:01Z", duration_ms: 1000, ...patch };
}
function page(patch: Record<string, unknown> = {}) {
    return { items: [entry()], total: 1, limit: 25, offset: 0, has_more: false, ...patch };
}
function summary(patch: Record<string, unknown> = {}) {
    return { entry_count: 1, max_entries: 5000, retention_days: 90,
        oldest_entry_at: "2026-10-01T12:00:01Z", newest_entry_at: "2026-10-01T12:00:01Z", ...patch };
}

beforeEach(() => { mockGet.mockReset(); mockPost.mockReset(); });
afterEach(() => { expect(mockPost).not.toHaveBeenCalled(); });

describe("Action History read contracts", () => {
    it("reads the fixture generated by Core's dedicated response models", async () => {
        mockGet.mockResolvedValueOnce({ data: nativeFixture.entry })
            .mockResolvedValueOnce({ data: nativeFixture.page })
            .mockResolvedValueOnce({ data: nativeFixture.summary })
            .mockResolvedValueOnce({ data: nativeFixture.providers });
        await expect(getProviderActionHistoryEntry(nativeFixture.entry.id)).resolves.toEqual(nativeFixture.entry);
        await expect(getProviderActionHistory()).resolves.toEqual(nativeFixture.page);
        await expect(getProviderActionHistorySummary()).resolves.toEqual(nativeFixture.summary);
        await expect(getProviderActionHistoryProviders()).resolves.toEqual(nativeFixture.providers);
        expect(mockGet).toHaveBeenCalledTimes(4);
    });

    it.each([true, false])("reads a complete audit result, success=%s", async (success) => {
        const data = entry({ success, status: success ? "succeeded" : "failed" });
        mockGet.mockResolvedValueOnce({ data });
        await expect(getProviderActionHistoryEntry("audit/one")).resolves.toEqual(data);
        expect(mockGet).toHaveBeenCalledExactlyOnceWith("/ops/actions/audit%2Fone");
    });

    it("honors the published Core defaults without defaulting outcome facts", async () => {
        const data = entry(); delete data.parameter_names; delete data.request_id;
        mockGet.mockResolvedValueOnce({ data: { ...data, future_metadata: { extra: true } } });
        await expect(getProviderActionHistoryEntry("audit/one")).resolves.toMatchObject({ parameter_names: [], request_id: null, success: true });
    });

    it.each([
        ["id", null], ["provider_id", ""], ["provider_name", []], ["action_id", " "], ["action_label", {}],
        ["status", "pending"], ["success", false], ["message", null], ["confirmed", "true"], ["destructive", 0],
        ["parameter_names", "service"], ["parameter_names", [{}]], ["request_id", {}],
        ["started_at", "2026-10-01T12:00:00"], ["completed_at", "2026-02-30T12:00:00Z"],
        ["duration_ms", "1000"], ["duration_ms", -1], ["duration_ms", Infinity], ["duration_ms", NaN],
    ])("rejects invalid %s=%s without reflecting its contents", async (field, value) => {
        mockGet.mockResolvedValueOnce({ data: entry({ message: "private record canary", [field]: value }) });
        const error = await getProviderActionHistoryEntry("audit/one").catch((error: unknown) => error);
        expect(error).toBeInstanceOf(ActionHistoryResponseError);
        expect(getAtlasErrorMessage(error, "fallback")).toBe("This audit record is incomplete or inconsistent. Try loading it again.");
        expect(getAtlasErrorMessage(error, "fallback")).not.toContain("private record canary");
    });

    it.each(["id", "provider_id", "provider_name", "action_id", "action_label", "status", "success", "message", "confirmed", "destructive", "started_at", "completed_at", "duration_ms"])("rejects missing required record fact %s", async (field) => {
        const data = entry(); delete data[field];
        mockGet.mockResolvedValueOnce({ data });
        await expect(getProviderActionHistoryEntry("audit/one")).rejects.toBeInstanceOf(ActionHistoryResponseError);
    });

    it("rejects another record before returning any of its evidence", async () => {
        mockGet.mockResolvedValueOnce({ data: { id: "foreign", message: "private foreign canary" } });
        await expect(getProviderActionHistoryEntry("audit/one")).rejects.toThrow("does not match this audit link");
    });

    it.each([401, 404, 503])("preserves HTTP %s failures without treating them as an empty report", async (status) => {
        const error = { isAxiosError: true, response: { status } };
        mockGet.mockRejectedValueOnce(error);
        await expect(getProviderActionHistoryEntry("audit/one")).rejects.toBe(error);
    });

    it("accepts complete pages and binds the requested page and controlled filters", async () => {
        const items = [entry({ id: "third", provider_id: "docker", status: "failed", success: false }), entry({ id: "fourth", provider_id: "docker", status: "failed", success: false })];
        mockGet.mockResolvedValueOnce({ data: page({ items, limit: 2, offset: 2, total: 5, has_more: true }) });
        await expect(getProviderActionHistory({ limit: 2, offset: 2, providerId: "docker", status: "failed" })).resolves.toMatchObject({ items, total: 5, offset: 2, limit: 2, has_more: true });
        expect(mockGet).toHaveBeenCalledWith("/ops/actions/page", { params: { limit: 2, offset: 2, provider_id: "docker", status: "failed", completed_from: undefined, completed_to: undefined, search: undefined } });
    });

    it("accepts an empty page beyond the end and the DTO's default empty items", async () => {
        mockGet.mockResolvedValueOnce({ data: { total: 1, offset: 25, limit: 25, has_more: false } });
        await expect(getProviderActionHistory({ offset: 25 })).resolves.toEqual({ items: [], total: 1, offset: 25, limit: 25, has_more: false });
    });

    it.each([
        { total: "1" }, { total: -1 }, { total: Number.MAX_SAFE_INTEGER + 1 }, { offset: 1 }, { limit: 0 }, { limit: 100 },
        { has_more: true }, { has_more: "false" }, { items: null }, { items: [{}] }, { items: [] }, { total: 2 },
        { items: [entry(), entry()], total: 2 }, { items: [entry({ success: false })] },
    ])("rejects inconsistent or incomplete page %j", async (patch) => {
        mockGet.mockResolvedValueOnce({ data: page(patch) });
        await expect(getProviderActionHistory()).rejects.toThrow("action history report is incomplete or inconsistent");
    });

    it.each([{ providerId: "different" }, { status: "failed" as const }])("rejects a page outside the requested controlled filter %j", async (query) => {
        mockGet.mockResolvedValueOnce({ data: page() });
        await expect(getProviderActionHistory(query)).rejects.toBeInstanceOf(ActionHistoryResponseError);
    });

    it("reads retention metadata with its nullable published defaults", async () => {
        mockGet.mockResolvedValueOnce({ data: { entry_count: 0, max_entries: 5000, retention_days: 90 } });
        await expect(getProviderActionHistorySummary()).resolves.toEqual({ entry_count: 0, max_entries: 5000, retention_days: 90, oldest_entry_at: null, newest_entry_at: null });
        expect(mockGet).toHaveBeenCalledExactlyOnceWith("/ops/actions/summary");
    });

    it.each([{ entry_count: "1" }, { max_entries: 0 }, { retention_days: 0 }, { retention_days: 1.5 }, { retention_days: Number.MAX_SAFE_INTEGER + 1 }, { entry_count: 5001 }, { oldest_entry_at: "2026-02-30T00:00:00Z" }, { newest_entry_at: "2026-01-01T00:00:00Z" }])("rejects malformed retention metadata %j", async (patch) => {
        mockGet.mockResolvedValueOnce({ data: summary(patch) });
        await expect(getProviderActionHistorySummary()).rejects.toBeInstanceOf(ActionHistoryResponseError);
    });

    it.each([[], [{ id: "fixture", name: "Example provider" }]].map((data) => ({ data })))("reads available provider choices %j", async ({ data }) => {
        mockGet.mockResolvedValueOnce({ data });
        await expect(getProviderActionHistoryProviders()).resolves.toEqual(data);
        expect(mockGet).toHaveBeenCalledExactlyOnceWith("/ops/actions/providers");
    });

    it.each([null, {}, ["fixture"], [{ id: "fixture" }], [{ id: "", name: "Blank identity" }], [{ id: "fixture", name: "One" }, { id: "fixture", name: "Two" }]].map((data) => ({ data })))("rejects unusable provider choices %j", async ({ data }) => {
        mockGet.mockResolvedValueOnce({ data });
        await expect(getProviderActionHistoryProviders()).rejects.toBeInstanceOf(ActionHistoryResponseError);
    });
});
