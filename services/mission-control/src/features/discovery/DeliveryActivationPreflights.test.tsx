import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, describe, expect, it, vi } from "vitest";
import { createDeliveryActivationPreflight, getDeliveryActivationPreflight, listDeliveryActivationPreflights } from "../../api/deliveryActivationPreflight";
import { deliveryActivationPreflightFixture as fixture } from "../../test/deliveryActivationPreflight";
import { DeliveryActivationPreflights } from "./DeliveryActivationPreflights";

vi.mock("../../api/deliveryActivationPreflight", () => ({ listDeliveryActivationPreflights: vi.fn(), getDeliveryActivationPreflight: vi.fn(), createDeliveryActivationPreflight: vi.fn(), deliveryActivationPreflightIdempotencyKey: vi.fn(() => "preflight-key") }));
describe("delivery activation preflight presentation", () => {
    beforeEach(() => { vi.resetAllMocks(); vi.mocked(listDeliveryActivationPreflights).mockResolvedValue({ preflights: [], nextCursor: null }); });
    it("renders loading, redacted error, empty, and blocked destination states", async () => {
        let reject: (error: Error) => void = () => undefined;
        vi.mocked(listDeliveryActivationPreflights).mockReturnValueOnce(new Promise((_, fail) => { reject = fail; }));
        const view = render(<DeliveryActivationPreflights csrfToken={null} />);
        expect(screen.getByText(/loading readiness checks/i)).toBeInTheDocument(); reject(new Error("credential /internal/path 10.0.0.1"));
        await waitFor(() => expect(screen.getByRole("alert")).toHaveTextContent(/currently unavailable/i));
        expect(view.container).not.toHaveTextContent(/credential \/internal|10\.0\.0\.1/i); view.unmount();
        render(<DeliveryActivationPreflights csrfToken={null} />);
        expect(await screen.findByText(/no readiness checks saved yet/i)).toBeInTheDocument();
        expect(screen.getByText(/a readiness check does not turn delivery on/i)).toBeInTheDocument();
        expect(screen.getByText(/expire after 30 seconds at most/i)).toBeInTheDocument();
        expect(screen.getByText(/Home Assistant remains blocked because its deployment artifact and required proof are missing/i)).toBeInTheDocument();
    });
    it("shows a plain result and keeps technical evidence and authority details available", async () => {
        vi.mocked(listDeliveryActivationPreflights).mockResolvedValueOnce({ preflights: [fixture], nextCursor: null });
        vi.mocked(getDeliveryActivationPreflight).mockResolvedValueOnce({ ...fixture, status: { ...fixture.status, lifecycle: "expired" }, audit_evidence: { ...fixture.audit_evidence, lifecycle: "expired" } });
        const user = userEvent.setup(); render(<DeliveryActivationPreflights csrfToken="csrf" />);
        const expectedLocalTime = (value: string) => new Intl.DateTimeFormat(undefined, { dateStyle: "medium", timeStyle: "medium" }).format(new Date(value));
        const savedChecks = await screen.findByRole("list", { name: "Saved delivery readiness checks" });
        const checkedAt = within(savedChecks).getByText(expectedLocalTime(fixture.result.evaluated_at), { exact: true });
        const expiresAt = within(savedChecks).getByText(expectedLocalTime(fixture.result.expires_at), { exact: true });
        expect(checkedAt).toHaveAttribute("datetime", fixture.result.evaluated_at);
        expect(expiresAt).toHaveAttribute("datetime", fixture.result.expires_at);
        expect(checkedAt.textContent).not.toBe(expiresAt.textContent);
        await user.click(await screen.findByRole("button", { name: /review readiness check/i }));
        const detail = screen.getByRole("heading", { name: "Readiness check details" }).parentElement!;
        expect(within(detail).getByText(/expired\. delivery is still off/i)).toBeInTheDocument();
        expect(within(detail).getByText(/not approval to send work/i)).toBeInTheDocument();
        await user.click(within(detail).getByText("Technical check details"));
        const observedAt = within(detail).getByText(expectedLocalTime(fixture.status.observed_at), { exact: true });
        expect(observedAt).toHaveAttribute("datetime", fixture.status.observed_at);
        expect(within(detail).getByText(fixture.result.preflight_fingerprint.value)).toBeInTheDocument();
        await user.click(within(detail).getByText("Earlier evidence linked to this check"));
        expect(within(detail).getAllByText(fixture.result.linkage.simulated_acknowledgement_evidence_fingerprint.value).length).toBeGreaterThan(0);
        await user.click(within(detail).getByText("Audit record"));
        expect(within(detail).getAllByText(fixture.audit_evidence.evidence_fingerprint.value).length).toBeGreaterThan(0);
        await user.click(within(detail).getByText("Authority flags"));
        expect(within(screen.getByLabelText("Fixed-false preflight authority flags")).getAllByText("false")).toHaveLength(11);
        expect(within(detail).getByText(/saving the same check request returns its original result/i)).toBeInTheDocument();
    });
    it("creates only durable evidence after exact confirmation and exposes no prohibited controls", async () => {
        vi.mocked(createDeliveryActivationPreflight).mockResolvedValueOnce(fixture); const user = userEvent.setup();
        const preparation = { schema: "delivery-activation-preflight-create-v1" as const, delivery_preparation_id: fixture.result.delivery_preparation_id, preparation_fingerprint: fixture.result.preparation_fingerprint };
        const { container } = render(<DeliveryActivationPreflights preparations={[preparation]} csrfToken="csrf" />);
        await user.click(await screen.findByRole("button", { name: "Check this preparation" }));
        expect(createDeliveryActivationPreflight).not.toHaveBeenCalled();
        const confirmation = screen.getByRole("heading", { name: "Confirm this readiness check" }).parentElement!;
        expect(within(confirmation).getByText(/will not turn delivery on, contact Agent, or send work/i)).toBeInTheDocument();
        await user.click(within(confirmation).getByText("Verify preparation fingerprint"));
        expect(within(confirmation).getByText(preparation.preparation_fingerprint.value)).toBeInTheDocument();
        await user.click(within(confirmation).getByRole("button", { name: "Save readiness check" }));
        expect(createDeliveryActivationPreflight).toHaveBeenCalledWith(preparation, "csrf", "preflight-key");
        expect(container.querySelectorAll("a, form")).toHaveLength(0);
        const labels = Array.from(container.querySelectorAll("button, a")).map((node) => node.textContent).join(" ");
        expect(labels).not.toMatch(/activate|send|deliver|run|install|execute|deploy|dispatch|start workflow|rollback/i);
    });
});
